
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE ROLE app_migrator
    LOGIN PASSWORD 'practice';

CREATE ROLE app_runtime
    LOGIN PASSWORD 'practice';

GRANT CONNECT ON DATABASE appdb TO app_migrator;
GRANT CONNECT ON DATABASE appdb TO app_runtime;

GRANT USAGE, CREATE ON SCHEMA public TO app_migrator;
GRANT USAGE ON SCHEMA public TO app_runtime;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA public TO app_runtime;

GRANT USAGE, SELECT, UPDATE
    ON ALL SEQUENCES IN SCHEMA public TO app_runtime;

ALTER DEFAULT PRIVILEGES FOR ROLE app_migrator IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_runtime;

ALTER DEFAULT PRIVILEGES FOR ROLE app_migrator IN SCHEMA public
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO app_runtime;
